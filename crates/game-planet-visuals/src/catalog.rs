#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum PlanetScaleTier {
    Small,
    Medium,
    Large,
}

impl PlanetScaleTier {
    pub const ALL: [Self; 3] = [Self::Small, Self::Medium, Self::Large];
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum PlanetScaleBand {
    Tiny,
    Dwarf,
    Small,
    Medium,
    Large,
    SuperEarth,
    SubNeptune,
    GasDwarf,
    Giant,
    SuperJovian,
}

impl PlanetScaleBand {
    pub const ALL: [Self; 10] = [
        Self::Tiny,
        Self::Dwarf,
        Self::Small,
        Self::Medium,
        Self::Large,
        Self::SuperEarth,
        Self::SubNeptune,
        Self::GasDwarf,
        Self::Giant,
        Self::SuperJovian,
    ];

    pub const fn radius_km(self) -> RangeF32 {
        match self {
            Self::Tiny => RangeF32::new(0.0, 500.0),
            Self::Dwarf => RangeF32::new(500.0, 1_500.0),
            Self::Small => RangeF32::new(1_500.0, 4_500.0),
            Self::Medium => RangeF32::new(4_500.0, 7_500.0),
            Self::Large => RangeF32::new(7_500.0, 10_000.0),
            Self::SuperEarth => RangeF32::new(10_000.0, 13_000.0),
            Self::SubNeptune => RangeF32::new(13_000.0, 24_000.0),
            Self::GasDwarf => RangeF32::new(24_000.0, 35_000.0),
            Self::Giant => RangeF32::new(35_000.0, 100_000.0),
            Self::SuperJovian => RangeF32::new(100_000.0, f32::MAX),
        }
    }

    pub const fn tier(self) -> PlanetScaleTier {
        match self {
            Self::Tiny | Self::Dwarf | Self::Small => PlanetScaleTier::Small,
            Self::Medium | Self::Large | Self::SuperEarth => PlanetScaleTier::Medium,
            Self::SubNeptune | Self::GasDwarf | Self::Giant | Self::SuperJovian => {
                PlanetScaleTier::Large
            }
        }
    }

    pub const fn from_radius_km(radius_km: f32) -> Self {
        if radius_km < 500.0 {
            Self::Tiny
        } else if radius_km < 1_500.0 {
            Self::Dwarf
        } else if radius_km < 4_500.0 {
            Self::Small
        } else if radius_km < 7_500.0 {
            Self::Medium
        } else if radius_km < 10_000.0 {
            Self::Large
        } else if radius_km < 13_000.0 {
            Self::SuperEarth
        } else if radius_km < 24_000.0 {
            Self::SubNeptune
        } else if radius_km < 35_000.0 {
            Self::GasDwarf
        } else if radius_km < 100_000.0 {
            Self::Giant
        } else {
            Self::SuperJovian
        }
    }

    pub const fn from_radius_range(radius_km: RangeF32) -> Self {
        Self::from_radius_km(radius_km.midpoint())
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct PlanetScaleProfile {
    pub band: PlanetScaleBand,
    pub tier: PlanetScaleTier,
    pub radius_km: RangeF32,
    pub band_radius_km: RangeF32,
}

#[derive(Debug, Clone, Copy, PartialEq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct PlanetCatalogEntry {
    pub id: &'static str,
    pub display_name: &'static str,
    pub family: PlanetFamily,
    pub archetype: PlanetArchetype,
    pub surface: SurfaceClass,
    pub atmosphere: AtmosphereClass,
    pub hydrosphere: HydrosphereClass,
    pub thermal: ThermalClass,
    pub geology: GeologyClass,
    pub biosphere: BiosphereClass,
    pub radius_km: RangeF32,
    pub mass_earth: RangeF32,
    pub gravity_g: RangeF32,
    pub temperature_c: RangeI16,
    pub pressure_atm: RangeF32,
    pub ocean_fraction: RangeF32,
    pub ice_fraction: RangeF32,
    pub cloud_fraction: RangeF32,
    pub volcanic_activity: RangeF32,
    pub albedo: RangeF32,
    pub palette: &'static [&'static str],
    pub generation_tags: &'static [&'static str],
    pub visual_notes: &'static str,
}

impl PlanetCatalogEntry {
    pub const fn scale_band(&self) -> PlanetScaleBand {
        PlanetScaleBand::from_radius_range(self.radius_km)
    }

    pub const fn scale_tier(&self) -> PlanetScaleTier {
        self.scale_band().tier()
    }

    pub const fn expected_scale(&self) -> PlanetScaleProfile {
        let band = self.scale_band();
        PlanetScaleProfile {
            band,
            tier: band.tier(),
            radius_km: self.radius_km,
            band_radius_km: band.radius_km(),
        }
    }
}

