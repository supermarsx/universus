    #[test]
    fn catalog_entries_expose_expected_scale_profiles() {
        let entries = catalog_entries();
        let mut covered_bands = BTreeSet::new();
        let mut covered_tiers = BTreeSet::new();

        for entry in entries {
            let scale = entry.expected_scale();
            assert_eq!(scale.band, entry.scale_band());
            assert_eq!(scale.tier, entry.scale_tier());
            assert_eq!(scale.radius_km, entry.radius_km);
            assert!(
                scale.band_radius_km.contains(entry.radius_km.midpoint()),
                "{} radius midpoint should fit its {:?} scale band",
                entry.id,
                scale.band
            );
            covered_bands.insert(scale.band);
            covered_tiers.insert(scale.tier);
        }

        for band in PlanetScaleBand::ALL {
            assert!(
                covered_bands.contains(&band),
                "catalog should include at least one {band:?} entry"
            );
        }

        for tier in PlanetScaleTier::ALL {
            assert!(
                covered_tiers.contains(&tier),
                "catalog should include {tier:?} generation scale entries"
            );
        }
    }
